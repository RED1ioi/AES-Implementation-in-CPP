        void key_schedule(uint32_t (&w)[44], uint8_t key[16]){
            for (int i = 0; i < 4; ++i)
            {
                w[i] = ((uint32_t)key[4 * i] << 24) | ((uint32_t)key[4 * i + 1] << 16) | ((uint32_t)key[4 * i + 2] << 8) | ((uint32_t)key[4 * i + 3]);
            }

            auto g = [this](uint32_t W, int rnd)
            {
                const uint8_t RC[10] = {0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36};
                uint8_t b0 = (W >> 16) & 0xFF;
                uint8_t b1 = (W >> 8) & 0xFF;
                uint8_t b2 = W & 0xFF;
                uint8_t b3 = (W >> 24) & 0xFF;
                b0 = sbox[b0];
                b1 = sbox[b1];
                b2 = sbox[b2];
                b3 = sbox[b3];
                b0 ^= RC[rnd - 1];
                return (uint32_t)((uint32_t)b0 << 24) | ((uint32_t)b1 << 16) | ((uint32_t)b2 << 8) | ((uint32_t)b3);
            };

            for (int i = 4; i < 44; ++i)
            {
                if (i % 4 == 0)
                    w[i] = w[i - 4] ^ g(w[i - 1], i / 4);
                else
                    w[i] = w[i - 4] ^ w[i - 1];
            }
        }

        void add_key(uint8_t (&b)[16], int rnd){
            int wordstart = rnd * 4;

            for (int col = 0; col < 4; ++col){
                uint32_t word = w[wordstart + col];

                uint8_t k0 = (word >> 24) & 0xFF;
                uint8_t k1 = (word >> 16) & 0xFF;
                uint8_t k2 = (word >> 8) & 0xFF;
                uint8_t k3 = word & 0xFF;

                b[col * 4] ^= k0;
                b[col * 4 + 1] ^= k1;
                b[col * 4 + 2] ^= k2;
                b[col * 4 + 3] ^= k3;
            }
        }

