        void encrypt(uint8_t (&state)[16]){
            add_key(state, 0);
            for (int r = 1; r <= 10; ++r){
                sub_bytes(state);
                shift_rows(state);
                if (r != 10)
                    mix_cols(state);
                add_key(state, r);
            }
        }

        void decrypt(uint8_t (&state)[16]){
            
            for (int r = 10; r >= 1; --r){
                add_key(state, r);
                if (r != 10)
                    inv_mix_cols(state);
                inv_shift_rows(state);
                inv_sub_bytes(state);
            }
            add_key(state,0);
        }

